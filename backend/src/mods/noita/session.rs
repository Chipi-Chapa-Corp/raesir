        fs::create_dir_all(profile.join("mods/testmod")).unwrap();
        fs::create_dir_all(profile.join("tools/test")).unwrap();
        fs::write(profile.join("mods/testmod/init.lua"), b"fixture mod").unwrap();
        fs::write(
            profile.join("tools/test/proxy"),
            b"#!/bin/sh\nprintf 'fixture settings' > \"$4\"\nmkdir -p \"$6\"\nexit 0\n",
        )
        .unwrap();
        fs::set_permissions(
            profile.join("tools/test/proxy"),
            fs::Permissions::from_mode(0o755),
        )
